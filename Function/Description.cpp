#include <iostream>
using namespace std;

/*
    FUNCTIONS IN C++
    ================
    
    A function is a reusable block of code that performs a specific task.
    It helps organize code, avoid repetition, and make programs modular.
    
    FUNCTION STRUCTURE:
    -------------------
    return_type function_name(parameters) {
        // function body
        return value;  // (if return_type is not void)
    }
    
    COMPONENTS:
    -----------
    1. return_type: Data type of value returned (int, double, void, etc.)
    2. function_name: Identifier to call the function
    3. parameters: Inputs to the function (optional)
    4. function body: Code to execute
    5. return statement: Returns value to caller (not needed for void)
*/


/*
    KEY POINTS ABOUT FUNCTIONS:
    ==========================
    
    1. MODULARITY: Functions break code into manageable pieces
    
    2. REUSABILITY: Write once, use many times
    
    3. PARAMETERS: Pass data to functions
    
    4. RETURN VALUE: Send result back to caller
    
    5. VOID FUNCTION: Doesn't return anything
    
    6. RECURSION: Function calling itself with base case
    
    7. FUNCTION OVERLOADING: Multiple functions with same name but different parameters
    
    8. SCOPE: Variables defined inside function are local to that function
*/
